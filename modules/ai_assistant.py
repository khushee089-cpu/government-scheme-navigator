def explain_scheme_fit(
    scheme_name: str,
    eval_result: Dict[str, Any],
    lang: str = "en"
) -> str:
    """
    Generate a clear, grounded explanation of why a scheme matches or does not match
    the user's profile based on the rule engine's findings.
    """
    status = eval_result.get("status", "Unknown")
    satisfied = eval_result.get("satisfied_conditions", [])
    unsatisfied = eval_result.get("unsatisfied_conditions", [])
    info_needed = eval_result.get("information_required", [])
    score = eval_result.get("relevance_score", 0)

    is_hindi = lang in ["hi", "hindi", "हिन्दी"]

    if is_hindi:
        lines = [f"### 📋 {scheme_name} के लिए पात्रता विश्लेषण (प्रासंगिकता स्कोर: {score}/100)"]
        lines.append(f"**वर्तमान स्थिति:** `{status}`\n")

        if satisfied:
            lines.append("**✅ पूरी की गई शर्तें:**")
            for s in satisfied:
                lines.append(f"- **{s.get('rule')}:** {s.get('detail')}")

        if unsatisfied:
            lines.append("\n**❌ अधूरी शर्तें (जिनके कारण अपात्रता हो सकती है):**")
            for u in unsatisfied:
                lines.append(f"- **{u.get('rule')}:** {u.get('reason', u.get('detail'))}")

        if info_needed:
            lines.append("\n**⚠️ अधिक जानकारी की आवश्यकता:**")
            for i in info_needed:
                lines.append(f"- **{i.get('rule')}:** {i.get('action')}")

        lines.append(
            "\n*सूचना: यह निष्कर्ष आधिकारिक नियमों पर आधारित एक प्रारंभिक मार्गदर्शन है। "
            "अंतिम पात्रता निर्णय सरकारी अधिकारियों और आधिकारिक पोर्टल द्वारा ही किया जाता है।*</br>"
        )
    else:
        lines = [f"### 📋 Eligibility Analysis for {scheme_name} (Relevance Score: {score}/100)"]
        lines.append(f"**Evaluation Status:** `{status}`\n")

        if satisfied:
            lines.append("**✅ Satisfied Eligibility Criteria:**")
            for s in satisfied:
                lines.append(f"- **{s.get('rule')}:** {s.get('detail')}")

        if unsatisfied:
            lines.append("\n**❌ Criteria Not Satisfied (Under Listed Rules):**")
            for u in unsatisfied:
                lines.append(f"- **{u.get('rule')}:** {u.get('reason', u.get('detail'))}")

        if info_needed:
            lines.append("\n**⚠️ Information Still Required to Confirm:**")
            for i in info_needed:
                lines.append(f"- **{i.get('rule')}:** {i.get('action')}")

        lines.append(
            "\n*Reminder: This evaluation is generated by the deterministic rule engine for guidance. "
            "Government authorities make the final decision upon document verification on official portals.*"
        )

    return "\n".join(lines)


def explain_checklist_summary(checklist: Dict[str, Any], lang: str = "en") -> str:
    """Generate a clean bulleted summary of all required documents."""
    is_hindi = lang in ["hi", "hindi", "हिन्दी"]
    total = checklist.get("total_documents", 0)
    categories = checklist.get("categories", {})

    if total == 0:
        return (
            "वर्तमान में कोई दस्तावेज़ आवश्यक नहीं हैं क्योंकि कोई योजना चुनी या योग्य नहीं पाई गई है।"
            if is_hindi else
            "No specific documents are currently required as no schemes are marked as potentially eligible."
        )

    if is_hindi:
        lines = [f"### 📑 आपके लिए आवश्यक मुख्य दस्तावेज़ों की सूची (कुल {total} दस्तावेज़):"]
        for cat_name, items in categories.items():
            lines.append(f"\n**{cat_name}:**")
            for item in items:
                schemes_str = ", ".join(item.get("schemes", []))
                lines.append(f"- **{item.get('document')}** (योजनाएं: {schemes_str})")
        lines.append(
            "\n*सुझाव: सभी दस्तावेज़ों की मूल प्रति और स्व-प्रमाणित फोटोकॉपी तैयार रखें।* "
            "आधार कार्ड में आपका मोबाइल नंबर और बैंक खाता अनिवार्य रूप से लिंक होना चाहिए।"
        )
    else:
        lines = [f"### 📑 Synthesized Document Checklist ({total} Key Documents):"]
        for cat_name, items in categories.items():
            lines.append(f"\n**{cat_name}:**")
            for item in items:
                schemes_str = ", ".join(item.get("schemes", []))
                lines.append(f"- **{item.get('document')}** (Required for: {schemes_str})")
        lines.append(
            "\n*Action Tip: Ensure your Aadhaar card is linked to your active mobile number "
            "and NPCI-mapped to your bank account for Direct Benefit Transfer (DBT).* "
        )

    return "\n".join(lines)


def _find_referenced_scheme(query: str, schemes: List[Dict[str, Any]]) -> Optional[Dict[str, Any]]:
    """Match query keywords to find the most relevant scheme from dataset."""
    q_lower = query.lower()

    # Direct keyword-to-scheme mapping for utmost precision
    keyword_map = [
        (["kisan", "pm-kisan", "pmkisan"], "SCHEME-001"),
        (["ayushman", "pm-jay", "pmjay", "jan arogya"], "SCHEME-002"),
        (["pmay-g", "awaas gramin", "rural housing"], "SCHEME-003"),
        (["pmay-u", "awaas urban", "urban housing"], "SCHEME-004"),
        (["ujjwala", "pmuy", "lpg", "gas cylinder"], "SCHEME-005"),
        (["mudra", "pmmy", "shishu", "kishore", "tarun"], "SCHEME-006"),
        (["vishwakarma", "artisan", "craftsperson"], "SCHEME-007"),
        (["svanidhi", "street vendor", "hawker", "thela"], "SCHEME-008"),
        (["pension", "nsap", "ignoaps", "old age"], "SCHEME-009"),
        (["scholarship", "post-matric", "sc/st student"], "SCHEME-010"),
        (["stand-up", "standup", "stand up"], "SCHEME-011"),
        (["atal", "apy"], "SCHEME-012"),
        (["suraksha", "pmsby", "bima", "accident"], "SCHEME-013"),
        (["sukanya", "ssy", "girl child"], "SCHEME-014"),
        (["kaushal", "pmkvy", "skill training"], "SCHEME-015"),
        (["matsya", "pmmsy", "fisher", "fish"], "SCHEME-016"),
        (["apprenticeship", "naps"], "SCHEME-017"),
        (["sumangala", "kanya sumangala"], "SCHEME-018"),
        (["magalir", "urimai", "tamil nadu"], "SCHEME-019"),
        (["yuva sambal", "sambal", "unemployment"], "SCHEME-020")
    ]

    for kws, sch_id in keyword_map:
        if any(kw in q_lower for kw in kws):
            for s in schemes:
                if s.get("id") == sch_id or s.get("scheme_id") == sch_id:
                    return s

    for s in schemes:
        name_val = s.get("scheme_name") or s.get("name", "")
        name_lower = name_val.lower()
        id_lower = (s.get("id") or s.get("scheme_id") or "").lower()
        hindi_name = s.get("hindi_name", "").lower()

        if id_lower and id_lower in q_lower:
            return s
        if name_lower and (name_lower in q_lower or q_lower in name_lower):
            return s
        if hindi_name and hindi_name in q_lower:
            return s

    return None


def grounded_fallback_assistant(
    query: str,
    user_profile: Dict[str, Any],
    evaluated_schemes: List[Dict[str, Any]],
    lang: str = "en"
) -> str:
    """
    Intelligent dataset-grounded assistant for offline mode (zero API key required).
    Answers citizen queries with 100% fidelity to the loaded scheme dataset.
    """
    is_hindi = lang in ["hi", "hindi", "हिन्दी"]
    q_lower = query.lower().strip()

    # Case 1: Greeting
    if any(w in q_lower for w in ["hello", "hi", "hey", "namaste", "नमस्ते", "help", "मदद"]):
        if is_hindi:
            return (
                "नमस्ते! मैं आपका सरकारी योजना सहायक हूँ। मैं आपको सरकारी योजनाओं के नियम, पात्रता, "
                "आवश्यक दस्तावेज़ और आवेदन की आधिकारिक जानकारी देने में मदद कर सकता हूँ।\n\n"
                "आप मुझसे किसी भी योजना के बारे में पूछ सकते हैं, जैसे:\n"
                "- *पीएम-किसान के लिए क्या दस्तावेज़ चाहिए?*\n"
                "- *मुद्रा योजना में कितना लोन मिलता है?*\n"
                "- *मेरी प्रोफाइल के अनुसार मुझे कौन सी योजना मिल सकती है?*"
            )
        return (
            "Hello! I am your Government Scheme Assistant. I can help you understand eligibility criteria, "
            "benefits, required documents, and official application portals based strictly on verified scheme data.\n\n"
            "You can ask me questions like:\n"
            "- *What documents do I need for PM-KISAN?*\n"
            "- *What are the benefits under Mudra Yojana?*\n"
            "- *Why am I eligible or ineligible for Ayushman Bharat?*"
        )

    # Case 2: Document checklist request
    if any(w in q_lower for w in ["document", "documents", "paper", "checklist", "दस्तावेज़", "कागजात"]):
        matched_scheme = _find_referenced_scheme(query, evaluated_schemes)
        if matched_scheme:
            docs = matched_scheme.get("required_documents", [])
            s_name = matched_scheme.get("scheme_name") or matched_scheme.get("name", "Scheme")
            if is_hindi:
                docs_formatted = "\n".join([f"- {d}" for d in docs])
                return (
                    f"**{s_name} के लिए आवश्यक दस्तावेज़:**\n\n"
                    f"{docs_formatted}\n\n"
                    f"🔗 **आधिकारिक सूचना पोर्टल:** {matched_scheme.get('official_information_url')}\n\n"
                    f"*ध्यान दें: आवेदन जमा करने से पहले आधिकारिक वेबसाइट पर नवीनतम अधिसूचना अवश्य देखें।*"
                )
            docs_formatted = "\n".join([f"- {d}" for d in docs])
            return (
                f"**Required Documents for {s_name}:**\n\n"
                f"{docs_formatted}\n\n"
                f"🔗 **Official Information Portal:** {matched_scheme.get('official_information_url')}\n\n"
                f"*Note: Always verify required formats and notary requirements on the official portal.*"
            )

    # Case 3: Specific scheme query (Benefits, Eligibility, Overview)
    matched_scheme = _find_referenced_scheme(query, evaluated_schemes)
    if matched_scheme:
        s_name = matched_scheme.get("scheme_name") or matched_scheme.get("name", "Scheme")
        dept = matched_scheme.get("department")
        desc = matched_scheme.get("short_description")
        benefits = matched_scheme.get("benefits")
        info_url = matched_scheme.get("official_information_url")
        app_url = matched_scheme.get("official_application_url")
        docs = matched_scheme.get("required_documents", [])
        status = matched_scheme.get("status", "Check in Find My Schemes")

        if is_hindi:
            return (
                f"### 🏛️ {s_name}\n"
                f"**मंत्रालय / विभाग:** {dept}\n\n"
                f"**विवरण:** {desc}\n\n"
                f"**प्रमुख लाभ:** {benefits}\n\n"
                f"**आपकी मूल्यांकन स्थिति:** `{status}`\n\n"
                f"**मुख्य दस्तावेज़:**\n" + "\n".join([f"- {d}" for d in docs[:4]]) + "\n\n"
                f"🔗 **आधिकारिक जानकारी लिंक:** [{info_url}]({info_url})\n"
                + (f"📝 **ऑनलाइन आवेदन लिंक:** [{app_url}]({app_url})\n" if app_url and "http" in app_url else "")
                + "\n*महत्वपूर्ण: अंतिम पात्रता संबंधित सरकारी विभाग द्वारा सत्यापन के बाद तय होती है।*"
            )

        return (
            f"### 🏛️ {s_name}\n"
            f"**Department / Ministry:** {dept}\n\n"
            f"**Description:** {desc}\n\n"
            f"**Stated Benefits:** {benefits}\n\n"
            f"**Your Profile Evaluation:** `{status}`\n\n"
            f"**Key Documents Needed:**\n" + "\n".join([f"- {d}" for d in docs[:4]]) + "\n\n"
            f"🔗 **Official Information:** [{info_url}]({info_url})\n"
            + (f"📝 **Application Portal:** [{app_url}]({app_url})\n" if app_url and "http" in app_url else "")
            + "\n*Notice: The scheme rules are governed by official notifications. Verify all details at the official portal.*"
        )

    # Case 4: General summary of user profile eligibility
    pot_eligible = [s for s in evaluated_schemes if s.get("status") == "Potentially Eligible"]
    if pot_eligible:
        top_schemes = [s.get("scheme_name", s.get("name")) for s in pot_eligible[:4]]
        if is_hindi:
            schemes_text = "\n".join([f"- **{name}**" for name in top_schemes])
            return (
                f"आपकी वर्तमान प्रोफ़ाइल के अनुसार, आप निम्नलिखित **{len(pot_eligible)} योजनाओं** के लिए संभावित रूप से पात्र प्रतीत होते हैं:\n\n"
                f"{schemes_text}\n\n"
                "विस्तृत नियम, अधूरी शर्तें और दस्तावेज़ देखने के लिए 'पात्रता परिणाम' और 'दस्तावेज़ चेकलिस्ट' टैब देखें।"
            )
        schemes_text = "\n".join([f"- **{name}**" for name in top_schemes])
        return (
            f"Based on your profile data, you appear **Potentially Eligible** for {len(pot_eligible)} schemes, including:\n\n"
            f"{schemes_text}\n\n"
            "Visit the **Eligibility Results** tab to review specific satisfied rules, and the **Document Checklist** tab to see what paperwork is required."
        )

    # Case 5: Default fallback
    if is_hindi:
        return (
            "मुझे आपके प्रश्न का सटीक उत्तर डेटाबेस में नहीं मिला या जानकारी को आधिकारिक सत्यापन की आवश्यकता है।\n\n"
            "कृपया किसी विशिष्ट योजना का नाम पूछें (जैसे पीएम-किसान, मुद्रा, आयुष्मान भारत, सुकन्या समृद्धि आदि), "
            "या सीधे भारत सरकार के आधिकारिक पोर्टल [myScheme.gov.in](https://www.myscheme.gov.in/) पर विवरण देखें।"
        )
    return (
        "I could not locate a definitive answer in the local verified dataset, or this information requires official verification.\n\n"
        "Please ask about a specific government scheme (such as PM-KISAN, Mudra, Ayushman Bharat, PMAY, Sukanya Samriddhi), "
        "or consult the official National Government Services Portal at [myScheme.gov.in](https://www.myscheme.gov.in/)."
    )


def query_llm_api(
    prompt: str,
    api_key: str,
    context_data: str
) -> Optional[str]:
    """
    Calls Gemini REST API if a valid key is provided.
    Adheres strictly to zero-hallucination ground rules.
    """
    if not api_key:
        return None

    # Google Gemini REST endpoint
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={api_key}"
    system_instruction = (
        "You are the Government Scheme Navigator Assistant. "
        "Answer user inquiries STRICTLY and ONLY using the provided scheme dataset context. "
        "CRITICAL RULES:\n"
        "1. Never invent or hallucinate scheme names, eligibility criteria, benefits, quotas, or links.\n"
        "2. If the context does not contain the answer, explicitly state: 'This information requires official verification on government portals.'\n"
        "3. Emphasize that the rule engine evaluates preliminary criteria and final approval is strictly up to government authorities.\n"
        "4. Keep responses concise, objective, polite, and helpful."
    )

    payload = {
        "contents": [
            {
                "parts": [
                    {"text": f"System Guidelines:\n{system_instruction}\n\nDataset Context:\n{context_data}\n\nUser Question:\n{prompt}"}
                ]
            }
        ],
        "generationConfig": {
            "temperature": 0.2,
            "maxOutputTokens": 600
        }
    }

    try:
        req = urllib.request.Request(
            url,
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json"},
            method="POST"
        )
        with urllib.request.urlopen(req, timeout=8) as response:
            res_data = json.loads(response.read().decode("utf-8"))
            candidates = res_data.get("candidates", [])
            if candidates:
                parts = candidates[0].get("content", {}).get("parts", [])
                if parts:
                    return parts[0].get("text")
    except Exception:
        # Fall back gracefully to local deterministic assistant
        return None

    return None


def ask_ai_assistant(
    query: str,
    user_profile: Dict[str, Any],
    evaluated_schemes: List[Dict[str, Any]],
    lang: str = "en",
    api_key: Optional[str] = None
) -> str:
    """
    Main entry point for AI Assistant with safe fallback.
    Tries LLM if API key configured; otherwise uses deterministic grounded assistant.
    """
    active_key = api_key or os.getenv("GEMINI_API_KEY") or os.getenv("AI_API_KEY")

    if active_key and active_key.strip():
        # Prepare condensed dataset context
        condensed = []
        for s in evaluated_schemes[:10]:
            condensed.append(
                f"Scheme: {s.get('scheme_name')} | Status: {s.get('status')} | "
                f"Benefits: {s.get('benefits')} | Documents: {', '.join(s.get('required_documents', []))} | "
                f"Official URL: {s.get('official_information_url')}"
            )
        context_str = "\n".join(condensed)

        llm_reply = query_llm_api(query, active_key, context_str)
        if llm_reply:
            return llm_reply

    # Safe deterministic offline fallback
    return grounded_fallback_assistant(query, user_profile, evaluated_schemes, lang)
