"""
AI Explanation Assistant Module.
Provides natural language explanations, answers citizen questions, and summarizes checklists.
Operates in Dual Mode:
  1. API Mode (when GEMINI_API_KEY or configurable LLM key is provided).
  2. Grounded Fallback Mode (100% offline, deterministic, zero-hallucination dataset reasoning).
"""

